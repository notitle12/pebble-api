-- 예약 ID가 기존 데이터와 충돌하면 전체 트랜잭션을 중단한다.
SELECT pg_advisory_xact_lock(58003100);
DO $$ BEGIN
  IF current_database() <> 'pebble' OR current_user <> 'pebble' THEN
    RAISE EXCEPTION '로컬 pebble DB/사용자만 지원합니다';
  END IF;
  IF EXISTS (SELECT 1 FROM member WHERE id=910000000000001000 AND
    (handle IS DISTINCT FROM 'local-preview' OR nickname <> '로컬검증' OR blog_name IS DISTINCT FROM '로컬 연동 검증')) THEN
    RAISE EXCEPTION '테스트 회원 ID 충돌';
  END IF;
  IF EXISTS (SELECT 1 FROM post WHERE id BETWEEN 910000000000001101 AND 910000000000001126 AND author_member_id <> 910000000000001000)
    OR EXISTS (SELECT 1 FROM project WHERE id BETWEEN 910000000000003001 AND 910000000000003003 AND owner_member_id <> 910000000000001000)
    OR EXISTS (SELECT 1 FROM post_block WHERE id BETWEEN 910000000000002002 AND 910000000000002053 AND post_id NOT BETWEEN 910000000000001101 AND 910000000000001126)
    OR EXISTS (SELECT 1 FROM project_feature WHERE id=910000000000004001 AND project_id <> 910000000000003001)
    OR EXISTS (SELECT 1 FROM project_link WHERE id=910000000000005001 AND project_id <> 910000000000003001) THEN
    RAISE EXCEPTION '테스트 콘텐츠 ID 충돌';
  END IF;
END $$;
